from app.extensions import db
from app.utils.time import now
from flask_login import UserMixin
from werkzeug.security import generate_password_hash, check_password_hash
from sqlalchemy import Index, text

class OrdemServico(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    numero_os=db.Column(db.String(40),unique=True,nullable=False,index=True)
    manutencao_id=db.Column(db.Integer,db.ForeignKey("manutencao.id"),unique=True,nullable=False)
    maquina_id=db.Column(db.Integer,db.ForeignKey("maquina.id"),nullable=False,index=True)
    data_abertura=db.Column(db.DateTime,default=now,nullable=False,index=True)
    data_inicio=db.Column(db.DateTime)
    data_finalizacao=db.Column(db.DateTime)
    tecnico_id=db.Column(db.Integer,db.ForeignKey("usuario.id"),index=True)
    defeito_relatado=db.Column(db.Text)
    diagnostico=db.Column(db.Text)
    servico_realizado=db.Column(db.Text)
    teste_final=db.Column(db.Text)
    observacoes=db.Column(db.Text)
    status=db.Column(db.String(30),default="ABERTA",nullable=False,index=True)
    valor_pecas=db.Column(db.Numeric(14,2),default=0,nullable=False)
    valor_mao_obra=db.Column(db.Numeric(14,2),default=0,nullable=False)
    valor_total=db.Column(db.Numeric(14,2),default=0,nullable=False)
    criado_em=db.Column(db.DateTime,default=now,nullable=False)
    atualizado_em=db.Column(db.DateTime,default=now,onupdate=now,nullable=False)
    maquina=db.relationship("Maquina",backref="ordens")
    manutencao=db.relationship("Manutencao",backref=db.backref("ordem",uselist=False))
    tecnico=db.relationship("Usuario")
    __table_args__=(db.CheckConstraint("status IN ('ABERTA','AGUARDANDO_DIAGNOSTICO','AGUARDANDO_PECA','EM_REPARO','AGUARDANDO_TESTE','FINALIZADA','CANCELADA')",name="ck_os_status"),)
class OrdemServicoItem(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    ordem_servico_id=db.Column(db.Integer,db.ForeignKey("ordem_servico.id"),nullable=False,index=True)
    checklist_item_id=db.Column(db.Integer,db.ForeignKey("checklist_item.id"),unique=True)
    componente=db.Column(db.String(180),nullable=False)
    acao=db.Column(db.String(30),nullable=False)
    descricao_problema=db.Column(db.Text)
    diagnostico=db.Column(db.Text)
    causa_provavel=db.Column(db.Text)
    peca_manual=db.Column(db.String(180))
    peca_id=db.Column(db.Integer,db.ForeignKey("peca.id"))
    quantidade=db.Column(db.Numeric(12,2),default=1,nullable=False)
    valor_unitario=db.Column(db.Numeric(14,2),default=0,nullable=False)
    valor_total=db.Column(db.Numeric(14,2),default=0,nullable=False)
    status=db.Column(db.String(30),default="PENDENTE",nullable=False)
    observacoes=db.Column(db.Text)
    criado_em=db.Column(db.DateTime,default=now,nullable=False)
    concluido_em=db.Column(db.DateTime)
    concluido_por=db.Column(db.Integer,db.ForeignKey("usuario.id"))
    ordem=db.relationship("OrdemServico",backref="itens")
    peca=db.relationship("Peca")
    __table_args__=(db.CheckConstraint("quantidade > 0",name="ck_item_quantidade"),db.CheckConstraint("acao IN ('REPARAR','SUBSTITUIR')",name="ck_item_acao"),db.CheckConstraint("status IN ('PENDENTE','AGUARDANDO_PECA','EM_REPARO','CONCLUIDO')",name="ck_item_status"))

class TesteFinal(db.Model):
    __test__ = False
    id=db.Column(db.Integer,primary_key=True)
    ordem_servico_id=db.Column(db.Integer,db.ForeignKey("ordem_servico.id"),nullable=False,index=True)
    eletrico=db.Column(db.String(20),nullable=False)
    funcionamento=db.Column(db.String(20),nullable=False)
    carga=db.Column(db.String(20),nullable=False)
    ventilacao=db.Column(db.String(20),nullable=False)
    painel=db.Column(db.String(20),nullable=False)
    observacoes=db.Column(db.Text)
    aprovado=db.Column(db.Boolean,nullable=False)
    usuario_id=db.Column(db.Integer,db.ForeignKey("usuario.id"),nullable=False)
    criado_em=db.Column(db.DateTime,default=now,nullable=False)
    ordem=db.relationship("OrdemServico",backref=db.backref("testes",order_by="TesteFinal.id"))